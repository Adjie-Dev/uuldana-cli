//! Normalized event taxonomy.
//!
//! Decoders turn transport frames into [`AgentEvent`]s. Each event carries a
//! [`Fidelity`] label so consumers know whether it came from a structured
//! provider message, from a heuristic (for example matching PTY screen text),
//! or from the supervisor itself.
//!
//! Events only describe what the provider exposed. Hidden reasoning or
//! undocumented internal state is never represented as transferable data.

use std::fmt;

use crate::error::ErrorClass;
use crate::ids::{NativeSessionId, PermissionRequestId, ProviderId, RunId, SessionId, ToolCallId};
use crate::lifecycle::RunState;
use crate::permission::{PermissionDecision, PermissionResolution};
use crate::session::NativeSessionLink;
use crate::time::Timestamp;
use crate::transport::ExitInfo;

/// How trustworthy an event is.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Fidelity {
    /// Parsed from a structured, documented provider or protocol message.
    Native,
    /// Inferred by a heuristic, for example matching terminal output text.
    Inferred,
    /// Generated by Uuldana, not by the provider.
    Synthetic,
}

/// Who authored a message chunk.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Role {
    /// The human user.
    User,
    /// The provider's agent.
    Agent,
}

/// Why a turn ended.
#[non_exhaustive]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum StopReason {
    /// The agent finished the turn.
    EndTurn,
    /// The model's output token limit was reached.
    MaxTokens,
    /// The per-turn request limit was reached.
    MaxTurnRequests,
    /// The agent refused to continue.
    Refusal,
    /// The turn was cancelled.
    Cancelled,
    /// A usage or rate limit ended the turn.
    LimitReached,
    /// The provider did not say, or said something unrecognized.
    Unknown,
}

/// Category of a tool call.
#[non_exhaustive]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ToolKind {
    /// Reading files or data.
    Read,
    /// Modifying files or data.
    Edit,
    /// Deleting files or data.
    Delete,
    /// Moving or renaming.
    Move,
    /// Searching.
    Search,
    /// Running commands or code.
    Execute,
    /// Internal planning step exposed as a tool call.
    Think,
    /// Fetching external content.
    Fetch,
    /// Switching the agent's mode.
    SwitchMode,
    /// Anything else.
    Other,
}

/// Status of a tool call.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ToolStatus {
    /// Not started yet, possibly waiting for permission.
    Pending,
    /// Running.
    InProgress,
    /// Finished successfully.
    Completed,
    /// Finished with an error.
    Failed,
}

/// Kind of limit a provider hit.
#[non_exhaustive]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum LimitKind {
    /// Plan or account usage quota exhausted until a reset.
    UsageQuota,
    /// Short-term request rate limit.
    RateLimit,
    /// The conversation no longer fits the model's context window.
    ContextWindow,
    /// A spending cap the user configured was reached.
    Budget,
    /// A limit of unrecognized kind.
    Unknown,
}

impl LimitKind {
    /// Stable snake_case name.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::UsageQuota => "usage_quota",
            Self::RateLimit => "rate_limit",
            Self::ContextWindow => "context_window",
            Self::Budget => "budget",
            Self::Unknown => "unknown",
        }
    }
}

impl fmt::Display for LimitKind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// A limit observed on the provider.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LimitSignal {
    /// Kind of limit.
    pub kind: LimitKind,
    /// When the limit resets, if the provider said.
    pub resets_at: Option<Timestamp>,
    /// Provider message, if any.
    pub message: Option<String>,
}

/// A normalized provider-agnostic event.
#[non_exhaustive]
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AgentEvent {
    /// The run moved between lifecycle states. Usually synthetic.
    RunStateChanged {
        /// Previous state.
        from: RunState,
        /// New state.
        to: RunState,
    },
    /// The provider's current native session identifier. If it differs from
    /// the one already recorded for the run, the change is recorded with
    /// [`NativeSessionLink::Unspecified`] because the relationship is unknown.
    NativeSessionIdentified {
        /// The native identifier.
        native: NativeSessionId,
    },
    /// The provider switched to another native session within the same run
    /// and the decoder knows how the sessions relate. Never fatal.
    NativeSessionChanged {
        /// The new current native identifier.
        native: NativeSessionId,
        /// Relationship to the previous native session.
        link: NativeSessionLink,
    },
    /// A turn started.
    TurnStarted,
    /// A turn ended.
    TurnEnded {
        /// Why it ended.
        reason: StopReason,
    },
    /// A chunk of visible message text.
    MessageChunk {
        /// Author.
        role: Role,
        /// Text.
        text: String,
    },
    /// A chunk of reasoning text the provider chose to display. Never
    /// includes hidden reasoning.
    ThoughtChunk {
        /// Text.
        text: String,
    },
    /// A tool call was announced.
    ToolCall {
        /// Tool call identifier.
        id: ToolCallId,
        /// Category.
        kind: ToolKind,
        /// Short human readable title.
        title: String,
        /// Initial status.
        status: ToolStatus,
    },
    /// A tool call changed.
    ToolCallUpdate {
        /// Tool call identifier.
        id: ToolCallId,
        /// New status, if changed.
        status: Option<ToolStatus>,
        /// New title, if changed.
        title: Option<String>,
    },
    /// The provider asked for permission.
    PermissionRequested {
        /// Request identifier.
        id: PermissionRequestId,
        /// Related tool call, if any.
        tool_call: Option<ToolCallId>,
        /// Decisions the provider offered.
        options: Vec<PermissionDecision>,
    },
    /// A permission request was answered.
    PermissionResolved {
        /// Request identifier.
        id: PermissionRequestId,
        /// The answer and who gave it.
        resolution: PermissionResolution,
    },
    /// Context usage changed.
    UsageUpdated {
        /// Tokens currently in context, if reported.
        context_used: Option<u64>,
        /// Context window size in tokens, if reported.
        context_size: Option<u64>,
    },
    /// The provider hit a limit.
    LimitReached(LimitSignal),
    /// The provider reported an error.
    ProviderError {
        /// Classification.
        class: ErrorClass,
        /// Message.
        message: String,
    },
    /// The provider process exited.
    ProcessExited(ExitInfo),
    /// Free-form diagnostic for logs.
    Diagnostic {
        /// Message.
        message: String,
    },
    /// Provider-specific data that has no normalized form. `payload` is an
    /// opaque string (often JSON) that consumers may ignore.
    Extension {
        /// Namespace, for example the provider id.
        namespace: String,
        /// Event name inside the namespace.
        name: String,
        /// Opaque payload.
        payload: String,
    },
}

/// Output of an event decoder, before the supervisor assigns sequence
/// numbers and identifiers.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DecodedEvent {
    /// Fidelity of the event.
    pub fidelity: Fidelity,
    /// The event.
    pub event: AgentEvent,
}

impl DecodedEvent {
    /// An event parsed from a structured provider message.
    pub fn native(event: AgentEvent) -> Self {
        Self {
            fidelity: Fidelity::Native,
            event,
        }
    }

    /// An event inferred heuristically.
    pub fn inferred(event: AgentEvent) -> Self {
        Self {
            fidelity: Fidelity::Inferred,
            event,
        }
    }

    /// An event generated by Uuldana.
    pub fn synthetic(event: AgentEvent) -> Self {
        Self {
            fidelity: Fidelity::Synthetic,
            event,
        }
    }
}

/// An event recorded in Uuldana's unified session history.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EventEnvelope {
    /// Monotonic sequence number within the session.
    pub seq: u64,
    /// When Uuldana observed the event.
    pub at: Timestamp,
    /// Session the event belongs to.
    pub session: SessionId,
    /// Run the event belongs to.
    pub run: RunId,
    /// Provider of that run.
    pub provider: ProviderId,
    /// Fidelity of the event.
    pub fidelity: Fidelity,
    /// The event.
    pub event: AgentEvent,
}

impl EventEnvelope {
    /// Wraps a decoded event with session bookkeeping.
    pub fn new(
        seq: u64,
        at: Timestamp,
        session: SessionId,
        run: RunId,
        provider: ProviderId,
        decoded: DecodedEvent,
    ) -> Self {
        Self {
            seq,
            at,
            session,
            run,
            provider,
            fidelity: decoded.fidelity,
            event: decoded.event,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decoded_event_constructors_set_fidelity() {
        assert_eq!(
            DecodedEvent::native(AgentEvent::TurnStarted).fidelity,
            Fidelity::Native
        );
        assert_eq!(
            DecodedEvent::inferred(AgentEvent::TurnStarted).fidelity,
            Fidelity::Inferred
        );
        assert_eq!(
            DecodedEvent::synthetic(AgentEvent::TurnStarted).fidelity,
            Fidelity::Synthetic
        );
    }

    #[test]
    fn envelope_preserves_decoded_fidelity() {
        let limit = AgentEvent::LimitReached(LimitSignal {
            kind: LimitKind::UsageQuota,
            resets_at: Some(Timestamp::from_unix_millis(10)),
            message: None,
        });
        let envelope = EventEnvelope::new(
            7,
            Timestamp::from_unix_millis(5),
            SessionId::new("s").unwrap(),
            RunId::new("r").unwrap(),
            ProviderId::new("example-agent").unwrap(),
            DecodedEvent::inferred(limit.clone()),
        );
        assert_eq!(envelope.seq, 7);
        assert_eq!(envelope.fidelity, Fidelity::Inferred);
        assert_eq!(envelope.event, limit);
    }

    #[test]
    fn limit_kind_names() {
        assert_eq!(LimitKind::UsageQuota.to_string(), "usage_quota");
        assert_eq!(LimitKind::Budget.as_str(), "budget");
    }
}
