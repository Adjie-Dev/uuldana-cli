<#
.SYNOPSIS
  Writes THIRD_PARTY_NOTICES.md: the license of every library built into the
  uuldana binary, with the license texts that ship with each one.

.DESCRIPTION
  Reads `cargo metadata` for each given target (default: the three the release
  archives are built for), so only libraries that end up in a binary are
  listed. Run it after the dependencies change. Needs the Rust toolchain on
  PATH (see WINDOWS_DEVELOPMENT.md) and network access for `cargo fetch`.
#>
param([string[]]$Target = @('x86_64-pc-windows-gnu', 'x86_64-unknown-linux-gnu', 'aarch64-apple-darwin'))
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

# The release archives are built for every target in the list, so the notices
# cover the union of what each one builds in.
$byId = @{}
$own = [Collections.Generic.HashSet[string]]::new()
foreach ($one in $Target) {
    # Sources of libraries that only another platform uses are not on disk yet.
    cargo fetch --locked --target $one
    if ($LASTEXITCODE -ne 0) { throw "cargo fetch failed for $one" }
    $meta = cargo metadata --format-version 1 --locked --filter-platform $one | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0) { throw "cargo metadata failed for $one" }
    foreach ($id in $meta.workspace_members) { [void]$own.Add($id) }
    foreach ($package in $meta.packages) { $byId[$package.id] = $package }
}
$packages = $byId.Values | Where-Object { -not $own.Contains($_.id) } | Sort-Object name, version
$Target = $Target -join ', '

$texts = @{}
$missing = @()
$index = [Collections.Generic.List[string]]::new()
foreach ($package in $packages) {
    $dir = Split-Path -Parent $package.manifest_path
    $files = Get-ChildItem -LiteralPath $dir -File -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING|UNLICENSE|NOTICE)' }
    if (-not $files) {
        $by = if ($package.authors) { ($package.authors -join ', ') -replace '\s*<[^>]*>', '' } else { 'author not stated in the package' }
        $where = if ($package.repository) { $package.repository } else { 'no repository stated' }
        $missing += "$($package.name) $($package.version): $($package.license); $by; $where"
    }
    foreach ($file in $files) {
        $text = (Get-Content -LiteralPath $file.FullName -Raw).Trim() -replace "`r`n", "`n"
        $hash = [BitConverter]::ToString([Security.Cryptography.SHA256]::Create().ComputeHash([Text.Encoding]::UTF8.GetBytes($text))).Replace('-', '')
        if (-not $texts.ContainsKey($hash)) { $texts[$hash] = @{ text = $text; users = [Collections.Generic.List[string]]::new() } }
        $texts[$hash].users.Add("$($package.name) $($package.version)")
    }
    $license = if ($package.license) { $package.license } else { 'see the license file of the crate' }
    $index.Add("- $($package.name) $($package.version): $license")
}

$out = [Text.StringBuilder]::new()
[void]$out.AppendLine('# Third party notices')
[void]$out.AppendLine()
[void]$out.AppendLine('uuldana itself is licensed under the MIT License (LICENSE-MIT). The binary is built with the libraries below, each under its own license. Generated by scripts/third-party-notices.ps1 for the targets ' + $Target + '.')
[void]$out.AppendLine()
[void]$out.AppendLine('## Libraries')
[void]$out.AppendLine()
foreach ($line in $index) { [void]$out.AppendLine($line) }
[void]$out.AppendLine()
[void]$out.AppendLine('## License texts')
foreach ($entry in $texts.GetEnumerator() | Sort-Object { $_.Value.users[0] }) {
    [void]$out.AppendLine()
    [void]$out.AppendLine('### ' + (($entry.Value.users | Select-Object -First 6) -join ', ') + $(if ($entry.Value.users.Count -gt 6) { ", and $($entry.Value.users.Count - 6) more" } else { '' }))
    [void]$out.AppendLine()
    [void]$out.AppendLine('```text')
    [void]$out.AppendLine($entry.Value.text)
    [void]$out.AppendLine('```')
}
if ($missing) {
    [void]$out.AppendLine()
    [void]$out.AppendLine('## Libraries that ship no license file')
    [void]$out.AppendLine()
    [void]$out.AppendLine('These packages carry no license file. The license each one declares, its authors as the package states them, and its repository are given.')
    [void]$out.AppendLine()
    foreach ($name in $missing) { [void]$out.AppendLine("- $name") }
}
[IO.File]::WriteAllText((Join-Path $root 'THIRD_PARTY_NOTICES.md'), $out.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host "libraries: $($packages.Count); distinct license texts: $($texts.Count); without a license file: $($missing.Count)"
